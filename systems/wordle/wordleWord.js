function normalizeWord(word) {
    return word
        .toLowerCase()
        .trim()
        .normalize("NFD")
        .replace(/[\u0300-\u036f]/g, "");
}


// ============================================================
// 🔎 FILTRAR EASY
// ============================================================

const filteredEasy = EASY.filter(word => {

    if (typeof word !== "string") {
        return false;
    }

    const clean = normalizeWord(word);

    // Solo letras
    if (!/^[a-zñ]+$/.test(clean)) {
        return false;
    }

    // 3 a 5 letras
    if (clean.length < 3 || clean.length > 5) {
        return false;
    }

    return true;
});


// ============================================================
// 🚫 ELIMINAR REPETIDAS
// ============================================================

const uniqueMap = new Map();

for (const word of filteredEasy) {

    const normalized = normalizeWord(word);

    if (!uniqueMap.has(normalized)) {
        uniqueMap.set(normalized, word);
    }
}


const EASY_UNIQUE = [...uniqueMap.values()];


// ============================================================
// 📅 WORDLE DAILY EASY
// ============================================================

if (EASY_UNIQUE.length < 750) {

    throw new Error(
        `❌ Wordle Daily Easy necesita 750 palabras únicas. ` +
        `Solo hay ${EASY_UNIQUE.length}.`
    );

}


// ============================================================
// 🎯 EXACTAMENTE 750
// ============================================================

const DAILY_EASY = EASY_UNIQUE.slice(0, 750);


// ============================================================
// 🛡️ VALIDACIÓN FINAL
// ============================================================

if (DAILY_EASY.length !== 750) {

    throw new Error(
        `❌ ERROR: Wordle Daily Easy tiene ` +
        `${DAILY_EASY.length} palabras.`
    );

}


const normalizedDaily = DAILY_EASY.map(normalizeWord);

const uniqueDaily = new Set(normalizedDaily);


if (uniqueDaily.size !== 750) {

    throw new Error(
        "❌ ERROR: existen palabras repetidas en Wordle Daily Easy."
    );

}


for (const word of DAILY_EASY) {

    const normalized = normalizeWord(word);

    if (
        normalized.length < 3 ||
        normalized.length > 5
    ) {

        throw new Error(
            `❌ ERROR: "${word}" no cumple 3-5 letras.`
        );

    }

}


